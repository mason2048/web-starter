import { createHash } from 'node:crypto'
import { readFile } from 'node:fs/promises'
import path from 'node:path'
import process from 'node:process'
import console from 'node:console'

const HTTP_METHODS = ['get', 'post', 'put', 'patch', 'delete']

function quote(value) {
  return JSON.stringify(value)
}

export function renderPrivateApiTypes(document, sourceBytes) {
  if (document.openapi !== '3.1.0') throw new Error('private API contract must use OpenAPI 3.1.0')
  const imports = document['x-web-starter-type-imports']
  if (!imports || typeof imports !== 'object') throw new Error('x-web-starter-type-imports is required')

  const operations = []
  const operationIds = new Set()
  for (const [contractPath, pathItem] of Object.entries(document.paths ?? {})) {
    for (const method of HTTP_METHODS) {
      const operation = pathItem?.[method]
      if (!operation) continue
      const operationId = operation.operationId
      const requestType = operation['x-web-starter-request-type']
      const responseType = operation['x-web-starter-response-type']
      if (typeof operationId !== 'string' || typeof requestType !== 'string' || typeof responseType !== 'string') {
        throw new Error(`${method.toUpperCase()} ${contractPath} is missing typed contract extensions`)
      }
      if (operationIds.has(operationId)) throw new Error(`duplicate operationId ${operationId}`)
      operationIds.add(operationId)
      operations.push({
        operationId,
        method: method.toUpperCase(),
        path: contractPath,
        csrf: operation['x-web-starter-csrf'] === true,
        requestType,
        responseType,
      })
    }
  }
  if (operations.length === 0) throw new Error('private API contract contains no operations')
  operations.sort((left, right) => left.operationId.localeCompare(right.operationId))

  const digest = createHash('sha256').update(sourceBytes).digest('hex')
  const lines = [
    '/* This file is generated by scripts/check-private-api-contract.mjs. */',
    `/* source-sha256: ${digest} */`,
  ]
  for (const [moduleName, names] of Object.entries(imports).sort(([left], [right]) => left.localeCompare(right))) {
    if (!Array.isArray(names) || names.some((name) => typeof name !== 'string')) {
      throw new Error(`invalid type import list for ${moduleName}`)
    }
    lines.push(`import type { ${[...names].sort().join(', ')} } from ${quote(moduleName)}`)
  }
  lines.push('', 'export interface PrivateApiOperationTypes {')
  for (const operation of operations) {
    lines.push(`  ${quote(operation.operationId)}: { request: ${operation.requestType}; response: ${operation.responseType} }`)
  }
  lines.push('}', '', 'export const PRIVATE_API_OPERATIONS = {')
  for (const operation of operations) {
    lines.push(
      `  ${quote(operation.operationId)}: { method: ${quote(operation.method)}, path: ${quote(operation.path)}, csrf: ${operation.csrf} },`,
    )
  }
  lines.push(
    '} as const',
    '',
    'export type PrivateApiOperationId = keyof PrivateApiOperationTypes',
    'export type PrivateApiRequest<K extends PrivateApiOperationId> = PrivateApiOperationTypes[K]["request"]',
    'export type PrivateApiResponse<K extends PrivateApiOperationId> = PrivateApiOperationTypes[K]["response"]',
    '',
  )
  return lines.join('\n')
}

export async function checkPrivateApiContract(rootDirectory) {
  const sourcePath = path.join(rootDirectory, 'contracts/private-api.openapi.json')
  const generatedPath = path.join(rootDirectory, 'src/api/generated/privateApiContract.ts')
  const sourceBytes = await readFile(sourcePath)
  const document = JSON.parse(sourceBytes.toString('utf8'))
  const expected = renderPrivateApiTypes(document, sourceBytes)
  const actual = await readFile(generatedPath, 'utf8')
  if (actual !== expected) {
    throw new Error('generated private API TypeScript is stale; run pnpm contract:write and review the diff')
  }
  return { operations: Object.keys(document.paths ?? {}).length, generatedPath }
}

export async function writePrivateApiContract(rootDirectory) {
  const sourcePath = path.join(rootDirectory, 'contracts/private-api.openapi.json')
  const sourceBytes = await readFile(sourcePath)
  const document = JSON.parse(sourceBytes.toString('utf8'))
  return renderPrivateApiTypes(document, sourceBytes)
}

const scriptPath = path.resolve(process.argv[1] ?? '')
if (scriptPath.endsWith('check-private-api-contract.mjs')) {
  const root = path.resolve(path.dirname(scriptPath), '..')
  checkPrivateApiContract(root)
    .then(({ operations }) => console.log(`private-api-contract PASS path-items=${operations}`))
    .catch((error) => {
      console.error(`private-api-contract FAIL ${error instanceof Error ? error.message : String(error)}`)
      process.exitCode = 1
    })
}
